
using System;
using System.Collections.Generic;
using System.Runtime.InteropServices;
using System.Text;

namespace C_Sharp_P58.Types
{
    internal class Classes
    {
        private int x;      // Це поле з доступом в межах класу
        protected int y;    // Це поле доступне також у спадкових класах
        public int w;       // Це поле доступне з усіх класів (не рекомендується)
    
        // Properties - Властивості. Конструкції, що формують аксесори автоматичноабо спрощено.
        public int X { get; set; }  // Регістрозалежність (case sensitivity) - різне сприйняття символів
                                    // різного розміру (не рекомендується створення елементів, імене яких відрізняються
                                    // лише регістром символів: x та X). Спосіб вирішення - додавання "_" до імен приватних елементів.
        private int _y;             // На авто - властивість: вводиться прихована змінна
        public int Y {              // та прямо описується аксесори: геттер і сеттер.
            get => _y;              // В таких формах можна, наприклад, додати перевірку
            set {                   // або додаткову обробку даних.
                 _y = value;        // Поширена практика - формування повідомлень про зміни
                Console.WriteLine($"Зафіксована зміна Y = {value}");
            }
        }
        // Властивості з різними аксесорами:
        public int A { get; private set; } // Читання - для всіх, а зміна - тільки в класі.
        public int B { get => 10; }   // Тільки для читання - як замінникк констант
        public int C { get; init; }   // Читання + ініціалізація (у конструкторі)
        public String TypeName { get => this.GetType().Name; }

        // Конструктори: може бути декілька з різними модифікаторами доступу.
        public Classes()  // Конструктор без параметрів
        {
            A = 10;
        }
        public Classes(int a)  // Конструктор з параметрами
        {
            A = a;
        }
        public Classes(int a, int c)  // Приватний конструктор  
        {
            A = a;
            C = c;
        }
        // Аналогічно до C++ описання будь - якого конструктора прибирає конструктор за замовчуванням.

        public void Demo() // Метод, доступний з усіх класів (для методів - ОК)
        {
            Console.WriteLine("Типи даних. Класи.");
            Y = 10; // Виклин set{} з передачею value = 10;
            Console.WriteLine(Y);
            Console.WriteLine("Type of object: " + TypeName);
        }
        class SubClass  // Nested type (nested class) - внутрішній тип (всередені іншого)
        {
            public int Sub {  get; set; }
        }
    }
}
/* 
 Типи даних. Класи.
 Типи даних у C# (.NET) - це об'єкти, які формуються (набираються) із заданого переліку "будівельних блоків".
 Їх перелік та особливості використання регулюються положенням CTS (Common Type System):
 - є декілька модифікаторів видності: для типів та їх частин.
    public, private - для всіх,
    internal - для типів,
    protected - для елементів
 - "будівельними блоками" є:
  = поля
  = методи
  = властивості - нові елементи платформи
  = конструктори
  = вкладені (nested) типи
*/